(async () => {
  const p = await db.project.create({
    data: {
      title: "养妹失策，社恐妹妹占有欲",
      genre: "校园，青春，甜宠，社恐",
      orientation: "9:16",
      targetEpisodes: 1,
      world: WORLD,
      style: STYLE,
      videoEngine: "h3",
      videoResolution: "768P",
    },
  });
  console.log("project", p.id);

  let ci = 0;
  for (const c of CHARACTERS) {
    await db.character.create({
      data: {
        projectId: p.id,
        name: c.name,
        age: c.age,
        role: c.role,
        personality: c.personality,
        catchphrase: c.catchphrase,
        relations: c.relations,
        order: ci++,
        personas: { create: c.personas.map((x, i) => ({ tag: x.tag, description: x.description, order: i })) },
      },
    });
  }
  let pi = 0;
  for (const x of PROPS) await db.prop.create({ data: { projectId: p.id, name: x.name, description: x.description, order: pi++ } });

  const ch = await db.chapter.create({ data: { projectId: p.id, index: 1, title: "开学第一天", sourceText: SOURCE } });
  console.log("chapter", ch.id);

  // 立刻排上人设三视图与道具概念图（生图没有时段折扣，先跑）
  const personas = await db.persona.findMany({ where: { character: { projectId: p.id } } });
  for (const x of personas) {
    await db.persona.update({ where: { id: x.id }, data: { status: "generating" } });
    await db.job.create({ data: { type: "persona.sheet", payload: JSON.stringify({ personaId: x.id }) } });
  }
  const props = await db.prop.findMany({ where: { projectId: p.id } });
  for (const x of props) {
    await db.prop.update({ where: { id: x.id }, data: { status: "generating" } });
    await db.job.create({ data: { type: "prop.sheet", payload: JSON.stringify({ propId: x.id }) } });
  }
  console.log("queued", personas.length, "sheets +", props.length, "props");
  require("fs").writeFileSync(process.env.TEMP + "/promo.txt", p.id + "\n" + ch.id);
  await db.$disconnect();
})();
