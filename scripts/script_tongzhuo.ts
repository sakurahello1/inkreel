async function main() {
  const projectId = process.argv[2];
  for (const [i, ep] of EPISODES.entries()) {
    const ch = await db.chapter.findFirst({ where: { projectId, index: i + 1 } });
    const speech = ep.text
      .split("\n")
      .filter((l) => /[：:]/.test(l))
      .join("")
      .replace(/[^一-鿿]/g, "").length;
    if (ch) {
      await db.chapter.update({ where: { id: ch.id }, data: { title: ep.title, sourceText: ep.text } });
      console.log(`${ep.title}  更新  约 ${speech} 字念白 / ${ep.seconds}s = ${(speech / ep.seconds).toFixed(2)} 字每秒`);
    } else {
      const c = await db.chapter.create({
        data: {
          projectId,
          index: i + 1,
          title: ep.title,
          sourceText: ep.text,
          endCardText: i === EPISODES.length - 1 ? "完整版\n番茄搜索：同桌说你压到我头发了" : "",
          endCardSecs: i === EPISODES.length - 1 ? 5 : 0,
        },
      });
      console.log(`${ep.title}  新建 ${c.id}`);
    }
  }
  await db.$disconnect();
}
main();
